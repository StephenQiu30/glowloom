type outputPublicationRepo struct {
	request             mediaapp.PublishOperationOutputRequest
	receipt             mediadomain.OperationOutputReceipt
	prepared, committed int
}

func (r *outputPublicationRepo) PrepareOutput(_ context.Context, req mediaapp.PublishOperationOutputRequest) (mediaapp.OperationOutputWork, error) {
	r.prepared++
	r.request = req
	return mediaapp.OperationOutputWork{Request: req, AssetID: uuid.New()}, nil
}
func (r *outputPublicationRepo) ResolveOutput(_ context.Context, _ mediaapp.PublishOperationOutputRequest) (mediadomain.OperationOutputReceipt, error) {
	if r.receipt.CommandID == uuid.Nil {
		return mediadomain.OperationOutputReceipt{}, mediadomain.ErrOutputPublicationUnknown
	}
	return r.receipt, nil
}
func (r *outputPublicationRepo) CommitOutput(_ context.Context, work mediaapp.OperationOutputWork, a mediadomain.MediaAsset, _ []mediadomain.Rendition, review mediaapp.OutputReview) (mediadomain.OperationOutputReceipt, error) {
	r.committed++
	r.receipt = mediadomain.OperationOutputReceipt{CommandID: work.Request.Command.ID, RequestSHA256: work.Request.Command.SHA256, PayloadSHA256: work.Request.Output.Digest(), Output: work.Request.Output, AssetID: a.ID, AssetRevision: 2, ModerationStatus: review.Status, ModerationDetail: review.Detail, State: "published"}
	return r.receipt, nil
}

type outputArchiver struct{ calls int }

func (a *outputArchiver) ArchiveOutput(_ context.Context, w mediaapp.OperationOutputWork, _ *mediaapp.Downloaded) (mediadomain.MediaAsset, []mediadomain.Rendition, error) {
	a.calls++
	return mediadomain.MediaAsset{ID: w.AssetID, ProjectID: w.Request.Output.ProjectID}, nil, nil
}

type outputReviewer struct{ calls int }

func (r *outputReviewer) ReviewOutput(_ context.Context, _ mediaapp.OperationOutputWork, _ mediadomain.MediaAsset) (mediaapp.OutputReview, error) {
	r.calls++
	return mediaapp.OutputReview{Status: "passed", Detail: []byte(`{"source":"fixture"}`)}, nil
}
func TestOperationOutputPublicationVerifiesCompleteBytesBeforeAnyArchive(t *testing.T) {
	for _, kind := range []string{"short", "wrong_hash", "trailing", "read_error"} {
		t.Run(kind, func(t *testing.T) {
			req, body := publicationRequest()
			repo := &outputPublicationRepo{}
			archiver := &outputArchiver{}
			review := &outputReviewer{}
			var reader io.Reader = bytes.NewReader(body)
			switch kind {
			case "short":
				reader = bytes.NewReader(body[:len(body)-1])
			case "wrong_hash":
				reader = strings.NewReader(strings.Repeat("x", len(body)))
			case "trailing":
				reader = bytes.NewReader(append(body, 'x'))
			case "read_error":
				reader = io.MultiReader(bytes.NewReader(body), publicationReadError{})
			}
			_, err := mediaapp.NewOutputPublisher(repo, archiver, review).Publish(t.Context(), req, reader)
			if err == nil || archiver.calls != 0 || review.calls != 0 || repo.committed != 0 {
				t.Fatalf("err=%v archive=%d review=%d committed=%d", err, archiver.calls, review.calls, repo.committed)
			}
		})
	}
}

type publicationReadError struct{}

func (publicationReadError) Read([]byte) (int, error) {
	return 0, errors.New("final transport failure")
}
func TestOperationOutputPublicationLostACKOnlyResolvesOriginal(t *testing.T) {
	req, body := publicationRequest()
	repo := &outputPublicationRepo{}
	archive := &outputArchiver{}
	review := &outputReviewer{}
	service := mediaapp.NewOutputPublisher(repo, archive, review)
	receipt, err := service.Publish(t.Context(), req, bytes.NewReader(body))
	if err != nil || receipt.State != "published" {
		t.Fatalf("%+v %v", receipt, err)
	}
	recovered, err := mediaapp.NewOutputPublisher(repo, nil, nil).Resolve(t.Context(), req)
	if err != nil || recovered.AssetID != receipt.AssetID || archive.calls != 1 || recovered.Output.Provider.ActualCostMicros != 12345 || recovered.Output.Provider.UsageSHA256 != req.Output.Provider.UsageSHA256 {
		t.Fatalf("lost original evidence: %+v %v", recovered, err)
	}
	raw := string(mustPublicationJSON(t, recovered))
	for _, secret := range []string{"bucket", "object_key", "profile_id"} {
		if strings.Contains(raw, secret) {
			t.Fatal("physical storage leaked", secret)
		}
	}
}
func mustPublicationJSON(t *testing.T, v any) []byte {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return b
}
func TestOperationOutputPublicationRequiresAllAuthorityAndWorkerEvidence(t *testing.T) {
	req, _ := publicationRequest()
	if err := mediaapp.ValidateOutputPublication(req); err != nil {
		t.Fatal(err)
	}
	for i := range req.Command.Authorities {
		copyReq := req
		copyReq.Command.Authorities = append([]writefence.Authority(nil), req.Command.Authorities[:i]...)
		copyReq.Command.Authorities = append(copyReq.Command.Authorities, req.Command.Authorities[i+1:]...)
		if mediaapp.ValidateOutputPublication(copyReq) == nil {
			t.Fatalf("accepted missing authority %d", i)
		}
	}
	req.Output.Worker.Epoch = 0
	if mediaapp.ValidateOutputPublication(req) == nil {
		t.Fatal("missing worker accepted")
	}
}
